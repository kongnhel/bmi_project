export const SUPPORTED_LANGUAGES = Object.freeze(['en', 'km']);
export const TRANSLATIONS = Object.freeze({ en, km });

export function t(language, key, variables) {
  const dictionary = TRANSLATIONS[language] ?? TRANSLATIONS.en;
  let value = dictionary[key] ?? TRANSLATIONS.en[key] ?? key;
  if (variables && typeof value === 'string') {
    value = value.replace(/\{(\w+)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
    ));
  }
  return value;
}

export function getTranslationKeys(language) {
  return Object.keys(TRANSLATIONS[language] ?? {});
}
